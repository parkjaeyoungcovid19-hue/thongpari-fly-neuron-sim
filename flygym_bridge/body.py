"""Owner-thread interface shared by the mock and real FlyGym bodies."""
from typing import Protocol, Any

class Body(Protocol):
    t: float
    physics_timestep_s: float
    max_physics_substeps: int | None = None
    lab_world: Any
    sim: Any = None

    def step(self, command, dt, tempo=1.0): ...
    def step_exact(self, command, substeps, tempo=1.0): ...
    def reset_body(self): ...
    def lab_state(self): ...
    def world_render_state(self): ...
    def ray_pick(self, ray_origin_mm, ray_direction): ...
    def apply_lab_command(self, command): ...
    def set_player_input(self, player_input): ...
    def clear_player_input(self): ...
    def drain_lab_events(self): ...
    def close(self):
        """Mocks have no native resources to release."""
